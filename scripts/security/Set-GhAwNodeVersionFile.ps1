<#
.SYNOPSIS
    Normalizes generated gh-aw detection jobs to use the repository Node version file.

.DESCRIPTION
    Finds canonical agentic workflow sources that opt in with the exact
    `hve-core-lock-node-version-file: .node-version` marker. For each source,
    validates that the corresponding lock was generated by the repository-pinned
    gh-aw version and that its detection job checks out `.node-version` at the
    trusted workflow commit before setup-node. The script makes that checkout
    unconditional, then replaces only gh-aw's hard-coded detection-job
    `node-version: '24'` input with `node-version-file: .node-version`.

    The operation fails closed on missing, duplicate, or structurally changed
    generated steps. Use Verify to check already-normalized locks without writing.

.PARAMETER RepoRoot
    Repository root. Defaults to the current Git repository root.

.PARAMETER Verify
    Validates that every opted-in lock is already normalized without modifying it.

.EXAMPLE
    ./scripts/security/Set-GhAwNodeVersionFile.ps1

.EXAMPLE
    ./scripts/security/Set-GhAwNodeVersionFile.ps1 -Verify

.NOTES
    Run this script immediately after `gh aw compile` with the gh-aw version
    pinned in scripts/security/tool-checksums.json.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [string]$RepoRoot,

    [Parameter(Mandatory = $false)]
    [switch]$Verify
)

$ErrorActionPreference = 'Stop'

#region Functions

function Get-RepositoryRoot {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $false)]
        [string]$Path
    )

    if (-not [string]::IsNullOrWhiteSpace($Path)) {
        return [System.IO.Path]::GetFullPath($Path)
    }

    $GitRoot = git rev-parse --show-toplevel 2>$null
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($GitRoot)) {
        throw 'Unable to resolve the repository root.'
    }

    return [System.IO.Path]::GetFullPath($GitRoot.Trim())
}

function Get-PinnedGhAwVersion {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Root
    )

    $ManifestPath = Join-Path $Root 'scripts/security/tool-checksums.json'
    if (-not (Test-Path -LiteralPath $ManifestPath -PathType Leaf)) {
        throw "Tool manifest not found: $ManifestPath"
    }

    $Manifest = Get-Content -LiteralPath $ManifestPath -Raw | ConvertFrom-Json
    $GhAwTools = @($Manifest.tools | Where-Object name -EQ 'gh-aw')
    if ($GhAwTools.Count -ne 1 -or [string]::IsNullOrWhiteSpace($GhAwTools[0].version)) {
        throw 'Tool manifest must contain exactly one versioned gh-aw entry.'
    }

    return [string]$GhAwTools[0].version
}

function Set-GhAwNodeVersionFile {
    [CmdletBinding()]
    [OutputType([pscustomobject[]])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Root,

        [Parameter(Mandatory = $false)]
        [switch]$VerifyOnly
    )

    $ResolvedRoot = Get-RepositoryRoot -Path $Root
    $WorkflowRoot = Join-Path $ResolvedRoot '.github/workflows'
    $PinnedVersion = Get-PinnedGhAwVersion -Root $ResolvedRoot
    $MarkerPattern = '(?m)^\s*#\s*hve-core-lock-node-version-file:\s*\.node-version\s*$'
    $Sources = @(
        Get-ChildItem -LiteralPath $WorkflowRoot -Filter '*.md' -File |
            Where-Object { (Get-Content -LiteralPath $_.FullName -Raw) -match $MarkerPattern }
    )

    if ($Sources.Count -eq 0) {
        throw 'No canonical workflows opt in to gh-aw Node version-file normalization.'
    }

    $Results = foreach ($Source in $Sources) {
        $SourceText = Get-Content -LiteralPath $Source.FullName -Raw
        if ([regex]::Matches($SourceText, $MarkerPattern).Count -ne 1) {
            throw "Canonical workflow must contain exactly one Node version-file marker: $($Source.FullName)"
        }

        $LockPath = [System.IO.Path]::ChangeExtension($Source.FullName, '.lock.yml')
        if (-not (Test-Path -LiteralPath $LockPath -PathType Leaf)) {
            throw "Generated workflow lock not found: $LockPath"
        }

        $LockText = Get-Content -LiteralPath $LockPath -Raw
        $CompilerMatches = [regex]::Matches($LockText, '(?m)^# gh-aw-metadata: .*"compiler_version":"v([^"]+)"')
        if ($CompilerMatches.Count -ne 1 -or $CompilerMatches[0].Groups[1].Value -ne $PinnedVersion) {
            throw "Generated lock compiler version does not match pinned gh-aw $PinnedVersion`: $LockPath"
        }

        $DetectionMatches = [regex]::Matches(
            $LockText,
            '(?ms)^  detection:\r?\n.*?(?=^  [A-Za-z0-9_-]+:\s*(?:#.*)?\r?$|\z)'
        )
        if ($DetectionMatches.Count -ne 1) {
            throw "Generated lock must contain exactly one detection job: $LockPath"
        }

        $Detection = $DetectionMatches[0].Value
        $SetupMatches = [regex]::Matches(
            $Detection,
            '(?m)^      - name: Setup Node\.js\r?\n        uses: actions/setup-node@[^\r\n]+\r?\n        with:\r?$'
        )
        if ($SetupMatches.Count -ne 1) {
            throw "Detection job must contain exactly one generated setup-node step: $LockPath"
        }

        $GeneratedCheckoutPattern = "(?ms)^      - name: Checkout runtime version\r?\n" +
            "        if: always\(\) && steps\.detection_guard\.outputs\.run_detection == 'true'\r?\n" +
            "        uses: actions/checkout@[^\r\n]+\r?\n" +
            "        with:\r?\n" +
            "          persist-credentials: false\r?\n" +
            '          ref: \$\{\{ github\.workflow_sha \}\}\r?\n' +
            "          sparse-checkout: \.node-version\r?\n" +
            "          sparse-checkout-cone-mode: false\r?$"
        $NormalizedCheckoutPattern = "(?ms)^      - name: Checkout runtime version\r?\n" +
            "        uses: actions/checkout@[^\r\n]+\r?\n" +
            "        with:\r?\n" +
            "          persist-credentials: false\r?\n" +
            '          ref: \$\{\{ github\.workflow_sha \}\}\r?\n' +
            "          sparse-checkout: \.node-version\r?\n" +
            "          sparse-checkout-cone-mode: false\r?$"
        $GeneratedCheckoutMatches = [regex]::Matches($Detection, $GeneratedCheckoutPattern)
        $NormalizedCheckoutMatches = [regex]::Matches($Detection, $NormalizedCheckoutPattern)
        if (($GeneratedCheckoutMatches.Count + $NormalizedCheckoutMatches.Count) -ne 1) {
            throw "Detection job must check out .node-version once from github.workflow_sha: $LockPath"
        }
        $CheckoutIndex = if ($GeneratedCheckoutMatches.Count -eq 1) {
            $GeneratedCheckoutMatches[0].Index
        }
        else {
            $NormalizedCheckoutMatches[0].Index
        }
        if ($CheckoutIndex -gt $SetupMatches[0].Index) {
            throw "Detection job must check out .node-version before setup-node: $LockPath"
        }

        $FloatingPattern = "(?m)^          node-version:\s*'24'\s*\r?$"
        $NormalizedPattern = '(?m)^          node-version-file:\s*\.node-version\s*\r?$'
        $FloatingMatches = [regex]::Matches($Detection, $FloatingPattern)
        $NormalizedMatches = [regex]::Matches($Detection, $NormalizedPattern)
        if (($FloatingMatches.Count + $NormalizedMatches.Count) -ne 1) {
            throw "Detection setup-node must contain exactly one supported Node version input: $LockPath"
        }

        if ($VerifyOnly -and ($FloatingMatches.Count -ne 0 -or $GeneratedCheckoutMatches.Count -ne 0)) {
            throw "Generated lock still needs gh-aw Node version-file normalization: $LockPath"
        }

        $Changed = $false
        if (-not $VerifyOnly -and ($FloatingMatches.Count -eq 1 -or $GeneratedCheckoutMatches.Count -eq 1)) {
            $NormalizedDetection = $Detection
            if ($GeneratedCheckoutMatches.Count -eq 1) {
                $NormalizedCheckout = $GeneratedCheckoutMatches[0].Value -replace (
                    "(?m)^        if: always\(\) && steps\.detection_guard\.outputs\.run_detection == 'true'\r?\n"
                ), ''
                $NormalizedDetection = $NormalizedDetection.Substring(0, $GeneratedCheckoutMatches[0].Index) +
                    $NormalizedCheckout +
                    $NormalizedDetection.Substring(
                        $GeneratedCheckoutMatches[0].Index + $GeneratedCheckoutMatches[0].Length
                    )
            }
            $NormalizedDetection = [regex]::Replace(
                $NormalizedDetection,
                $FloatingPattern,
                '          node-version-file: .node-version',
                1
            )
            $LockText = $LockText.Substring(0, $DetectionMatches[0].Index) +
                $NormalizedDetection +
                $LockText.Substring($DetectionMatches[0].Index + $DetectionMatches[0].Length)
            [System.IO.File]::WriteAllText(
                $LockPath,
                $LockText,
                [System.Text.UTF8Encoding]::new($false)
            )
            $Changed = $true
        }

        [pscustomobject]@{
            Source = [System.IO.Path]::GetRelativePath($ResolvedRoot, $Source.FullName)
            Lock = [System.IO.Path]::GetRelativePath($ResolvedRoot, $LockPath)
            Changed = $Changed
        }
    }

    return @($Results)
}

#endregion Functions

#region Main Execution

if ($MyInvocation.InvocationName -ne '.') {
    try {
        $ResolvedRoot = Get-RepositoryRoot -Path $RepoRoot
        $Results = Set-GhAwNodeVersionFile -Root $ResolvedRoot -VerifyOnly:$Verify
        $ChangedCount = @($Results | Where-Object Changed).Count
        $Mode = if ($Verify) { 'verified' } else { 'normalized' }
        Write-Host "gh-aw Node version-file locks $Mode`: $($Results.Count) checked, $ChangedCount changed" -ForegroundColor Green
    }
    catch {
        Write-Error -ErrorAction Continue "Set-GhAwNodeVersionFile failed: $($_.Exception.Message)"
        exit 1
    }
}

#endregion Main Execution
