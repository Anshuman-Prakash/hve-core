BeforeAll {
    . (Join-Path $PSScriptRoot '../../security/Set-GhAwNodeVersionFile.ps1')

    function script:New-GhAwFixture {
        param(
            [string]$DetectionVersionInput = "          node-version: '24'",
            [switch]$WithoutCheckout,
            [switch]$WithoutMarker,
            [switch]$NormalizedCheckout
        )

        $Root = Join-Path $TestDrive ([guid]::NewGuid().ToString())
        $WorkflowRoot = Join-Path $Root '.github/workflows'
        $SecurityRoot = Join-Path $Root 'scripts/security'
        New-Item -ItemType Directory -Path $WorkflowRoot, $SecurityRoot -Force | Out-Null

        @{ tools = @(@{ name = 'gh-aw'; version = '0.89.21' }) } |
            ConvertTo-Json -Depth 5 |
            Set-Content -LiteralPath (Join-Path $SecurityRoot 'tool-checksums.json') -Encoding utf8

        $Marker = if ($WithoutMarker) { '' } else { '    # hve-core-lock-node-version-file: .node-version' }
        @"
---
jobs:
  threat-detection:
$Marker
    steps: []
---
"@ | Set-Content -LiteralPath (Join-Path $WorkflowRoot 'fixture.md') -Encoding utf8

        $Checkout = if ($WithoutCheckout) {
            ''
        }
        else {
            $Condition = if ($NormalizedCheckout) {
                ''
            }
            else {
                "        if: always() && steps.detection_guard.outputs.run_detection == 'true'`n"
            }
            @"
      - name: Checkout runtime version
$Condition        uses: actions/checkout@$('a' * 40)
        with:
          persist-credentials: false
          ref: `${{ github.workflow_sha }}
          sparse-checkout: .node-version
          sparse-checkout-cone-mode: false
"@
        }

        @"
# gh-aw-metadata: {"compiler_version":"v0.89.21"}
jobs:
  agent:
    steps:
      - name: Setup Node.js
        uses: actions/setup-node@$('b' * 40)
        with:
          node-version: '24.21.0'
  detection:
    steps:
$Checkout
      - name: Setup Node.js
        uses: actions/setup-node@$('b' * 40)
        with:
$DetectionVersionInput
          package-manager-cache: false
  conclusion:
    steps: []
"@ | Set-Content -LiteralPath (Join-Path $WorkflowRoot 'fixture.lock.yml') -Encoding utf8

        return $Root
    }
}

Describe 'Set-GhAwNodeVersionFile' -Tag 'Unit' {
    It 'normalizes only the opted-in detection setup-node input' {
        $Root = New-GhAwFixture

        $Result = Set-GhAwNodeVersionFile -Root $Root
        $Lock = Get-Content -LiteralPath (Join-Path $Root '.github/workflows/fixture.lock.yml') -Raw

        $Result.Count | Should -Be 1
        $Result[0].Changed | Should -BeTrue
        $Lock | Should -Match 'node-version-file: \.node-version'
        $Lock | Should -Match "node-version: '24\.21\.0'"
        $Lock | Should -Not -Match "node-version: '24'"
        $Lock | Should -Not -Match "if: always\(\) && steps\.detection_guard\.outputs\.run_detection == 'true'"
        $Lock | Should -Match 'ref: \$\{\{ github\.workflow_sha \}\}'
    }

    It 'verifies an already-normalized generated lock without rewriting it' {
        $Root = New-GhAwFixture -DetectionVersionInput '          node-version-file: .node-version' -NormalizedCheckout
        $LockPath = Join-Path $Root '.github/workflows/fixture.lock.yml'
        $Before = [System.IO.File]::ReadAllBytes($LockPath)

        $Result = Set-GhAwNodeVersionFile -Root $Root -VerifyOnly

        $Result[0].Changed | Should -BeFalse
        [System.IO.File]::ReadAllBytes($LockPath) | Should -Be $Before
    }

    It 'rejects verification while the generated floating input remains' {
        $Root = New-GhAwFixture

        { Set-GhAwNodeVersionFile -Root $Root -VerifyOnly } |
            Should -Throw '*still needs gh-aw Node version-file normalization*'
    }

    It 'rejects normalization when the detection job lacks the version-file checkout' {
        $Root = New-GhAwFixture -WithoutCheckout

        { Set-GhAwNodeVersionFile -Root $Root } |
            Should -Throw '*check out .node-version once from github.workflow_sha*'
    }

    It 'does not normalize an unmarked canonical workflow' {
        $Root = New-GhAwFixture -WithoutMarker

        { Set-GhAwNodeVersionFile -Root $Root } |
            Should -Throw '*No canonical workflows opt in*'
    }

    It 'rejects locks generated by a different compiler version' {
        $Root = New-GhAwFixture
        $LockPath = Join-Path $Root '.github/workflows/fixture.lock.yml'
        (Get-Content -LiteralPath $LockPath -Raw).Replace(
            '"compiler_version":"v0.89.21"',
            '"compiler_version":"v0.90.0"'
        ) | Set-Content -LiteralPath $LockPath -Encoding utf8

        { Set-GhAwNodeVersionFile -Root $Root } |
            Should -Throw '*compiler version does not match*'
    }
}
